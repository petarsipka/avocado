package com.app;

public enum RightType {
    CARE_MEALS,         // meals and drinks (Art. 9(1)(a))
    CARE_PHONE,         // two free phone calls (Art. 9(2))
    HOTEL,              // accommodation (Art. 9(1)(b))
    HOTEL_TRANSPORT,    // transport airport-hotel (Art. 9(1)(c))
    REFUND,             // ticket refund (Art. 8(1)(a))
    REROUTING,          // rerouting (Art. 8(1)(b))
    ALTERNATIVE_FLIGHT, // alternative flight without surcharge (Art. 8)
    COMPENSATION,       // financial compensation right (Art. 7)
    CARE_PRIORITY       // priority care for vulnerable passengers (Art. 9(3), 11)
}
